classdef IsSafeRelativePathTest < matlab.unittest.TestCase
    % IsSafeRelativePathTest - Unit tests for ebrains.bucket.internal.isSafeRelativePath

    properties (TestParameter)
        % Names that stay below the folder they are joined to
        SafeName = struct( ...
            "FileName", "a.txt", ...
            "NestedName", "a/b.txt", ...
            "DeeplyNestedName", "a/b/c.txt", ...
            "DotsInsideSegment", "a..b/v1.2.txt", ...
            "NameWithSpaces", "a folder/a file with spaces.txt", ...
            "NonAsciiName", "données/été.txt", ...
            "DriveInLaterSegment", "a/C:/b.txt", ...
            "ColonAfterTwoLetters", "ab:c.txt", ...
            "ColonInsideName", "log 10:30.txt")

        % Names that could leave the folder or point elsewhere
        UnsafeName = struct( ...
            "EmptyName", "", ...
            "CurrentFolder", ".", ...
            "ParentFolder", "..", ...
            "ParentFolderWithTrailingSlash", "../", ...
            "LeadingParentSegment", "../x", ...
            "InnerParentSegment", "a/../x", ...
            "InnerCurrentSegment", "a/./b", ...
            "DoubledSlash", "a//b", ...
            "TrailingSlash", "a/", ...
            "LeadingSlash", "/a", ...
            "OnlySlash", "/", ...
            "DoubleLeadingSlash", "//srv/x", ...
            "Backslash", "a\b", ...
            "WindowsUncPath", "\\srv\x", ...
            "WindowsDrivePath", "C:\x", ...
            "WindowsDriveWithSlash", "C:/x", ...
            "WindowsDriveWithoutSlash", "c:x", ...
            "WindowsDriveAlone", "C:")
    end

    methods (Test)
        function testAcceptsNameBelowFolder(testCase, SafeName)
            testCase.verifyTrue(ebrains.bucket.internal.isSafeRelativePath(SafeName));
        end

        function testRejectsNameThatCouldLeaveFolder(testCase, UnsafeName)
            testCase.verifyFalse(ebrains.bucket.internal.isSafeRelativePath(UnsafeName));
        end

        function testReturnsOneResultPerNameInShapeOfInput(testCase)
            names = ["a.txt", "../x"; "a/b.txt", "a\b"];

            tf = ebrains.bucket.internal.isSafeRelativePath(names);

            testCase.verifyEqual(tf, [true, false; true, false]);
        end
    end
end
