classdef FormatDurationTest < matlab.unittest.TestCase
    % FormatDurationTest - Unit tests for ebrains.bucket.app.internal.formatDuration
    %
    % Each case of the Duration parameter is a number of seconds and the
    % text expected for it. The cases sit on both sides of each value at
    % which the unit or the rounding step changes.

    properties (TestParameter)
        Duration = struct( ...
            "ZeroIsAtLeastTenSeconds", {{0, "10 seconds"}}, ...
            "SecondsRoundToTens", {{44, "40 seconds"}}, ...
            "LastValueInSeconds", {{54.9, "50 seconds"}}, ...
            "FirstValueInMinutes", {{55, "1 minute"}}, ...
            "OneMinuteIsSingular", {{89, "1 minute"}}, ...
            "MinutesRoundToWhole", {{360, "6 minutes"}}, ...
            "LastValueInMinutes", {{3569, "59 minutes"}}, ...
            "FirstValueInHours", {{3570, "1 hour"}}, ...
            "OneHourIsSingular", {{3600, "1 hour"}}, ...
            "MinutesPastTheHourRoundDown", {{3720, "1 hour"}}, ...
            "MinutesPastTheHourRoundUp", {{3750, "1 hour 5 minutes"}}, ...
            "HourWithMinutes", {{4140, "1 hour 10 minutes"}}, ...
            "WholeHoursHaveNoMinutes", {{7200, "2 hours"}}, ...
            "MinutesRoundUpToTheNextHour", {{7080, "2 hours"}}, ...
            "SeveralHoursWithMinutes", {{41400, "11 hours 30 minutes"}})
    end

    methods (Test)
        function testDurationIsRoundedAndGivenItsUnit(testCase, Duration)
            [durationSeconds, expectedText] = Duration{:};

            text = ebrains.bucket.app.internal.formatDuration(durationSeconds);

            testCase.verifyEqual(text, expectedText);
        end

        function testNegativeDurationIsRejected(testCase)
            testCase.verifyError(@() ebrains.bucket.app.internal.formatDuration(-1), ...
                "MATLAB:validators:mustBeNonnegative");
        end

        function testInfiniteDurationIsRejected(testCase)
            testCase.verifyError(@() ebrains.bucket.app.internal.formatDuration(Inf), ...
                "MATLAB:validators:mustBeFinite");
        end
    end
end
